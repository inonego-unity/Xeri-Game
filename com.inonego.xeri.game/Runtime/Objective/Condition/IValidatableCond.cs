# 설명
Spec을 등록할 때 Validator가 정적으로 검사할 수 있는 Condition이 구현하는 내부 계약.

# 특이사항, 제약사항
Condition이 자신의 참조와 임계값을 직접 검사하므로 Validator는 Condition의 종류를 알지 못한다.
Core 논리 조합(AND/OR/NOT) 안쪽의 Condition도 Validator가 방문해 호출한다.
임의 사용자 ICond는 구현하지 않으므로 정적 검사를 받지 않는다.
