namespace inonego.Xeri.Game.Objective
{
    // ============================================================
    /// <summary>
    /// 정적 검사를 스스로 선언하는 Condition.
    /// </summary>
    // ============================================================
    internal interface IValidatableCond
    {
        // --------------------------------------------------------------------------------
        /// <summary>
        /// 이 Condition이 놓인 위치의 범위에서 참조와 임계값이 유효한지 검사하고 오류를 범위에 알린다.
        /// </summary>
        // --------------------------------------------------------------------------------
        void Validate(CondValidateScope scope);
    }
}
