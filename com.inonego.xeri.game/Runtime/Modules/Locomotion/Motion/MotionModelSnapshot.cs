# 설명
Motion Model의 층 항목(Override·배율·외부 속도) 값과 그 상태를 보관하는 Snapshot을 정의한다.

# 특이사항, 제약사항
항목은 값 구조체 배열이므로 같은 Snapshot을 재사용하면 Capture에 할당이 없다.
기본 의도는 한 Tick 수명이라 Snapshot에 넣지 않는다. StepVersion 같은 발급 토큰도 넣지 않는다.
========================================================================= BLOCK_HEADER_END */

using System;

using UnityEngine;

using inonego;
using inonego.Xeri;
using inonego.Xeri.Serializable;

namespace inonego.Xeri.Game.Motion
{
    // ============================================================
    /// <summary>
    /// 아래 층을 가리는 Override 항목.
    /// </summary>
    // ============================================================
    internal struct MotionOverrideEntry
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 항목 식별자.
        /// </summary>
        // ------------------------------------------------------------
        public MotionSourceKey Source;

        // ------------------------------------------------------------
        /// <summary>
        /// 항목이 덮는 채널.
        /// </summary>
        // ------------------------------------------------------------
        public MotionChannel Channels;

        // ------------------------------------------------------------
        /// <summary>
        /// Override 우선순위. 높을수록 위층이다.
        /// </summary>
        // ------------------------------------------------------------
        public int Priority;

        // ------------------------------------------------------------
        /// <summary>
        /// 같은 우선순위 안의 등록 순서.
        /// </summary>
        // ------------------------------------------------------------
        public long Sequence;

        // ------------------------------------------------------------
        /// <summary>
        /// Override가 주는 선속도.
        /// </summary>
        // ------------------------------------------------------------
        public Vector3 Linear;

        // ------------------------------------------------------------
        /// <summary>
        /// Override가 주는 각속도.
        /// </summary>
        // ------------------------------------------------------------
        public Vector3 Angular;

        // ------------------------------------------------------------
        /// <summary>
        /// 지속 시간 제한 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasDuration;

        // ------------------------------------------------------------
        /// <summary>
        /// 남은 지속 시간(초).
        /// </summary>
        // ------------------------------------------------------------
        public float Remaining;

        // ------------------------------------------------------------
        /// <summary>
        /// 평가할 Track 식별자. 0이면 Track이 없다.
        /// </summary>
        // ------------------------------------------------------------
        public int TrackID;

        // ------------------------------------------------------------
        /// <summary>
        /// Track 재생 속도 배율.
        /// </summary>
        // ------------------------------------------------------------
        public float TrackRate;

        // ------------------------------------------------------------
        /// <summary>
        /// Track 재생 경과 시간(초).
        /// </summary>
        // ------------------------------------------------------------
        public float TrackElapsed;

        // ------------------------------------------------------------
        /// <summary>
        /// 사용처가 정한 동작 식별자.
        /// </summary>
        // ------------------------------------------------------------
        public int ActionID;

        // ------------------------------------------------------------
        /// <summary>
        /// Override가 시작된 Tick.
        /// </summary>
        // ------------------------------------------------------------
        public long StartTick;
    }

    // ============================================================
    /// <summary>
    /// 채널·층별 제어 배율 항목.
    /// </summary>
    // ============================================================
    internal struct MotionScaleEntry
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 항목 식별자.
        /// </summary>
        // ------------------------------------------------------------
        public MotionSourceKey Source;

        // ------------------------------------------------------------
        /// <summary>
        /// 적용 채널.
        /// </summary>
        // ------------------------------------------------------------
        public MotionChannel Channels;

        // ------------------------------------------------------------
        /// <summary>
        /// 적용 층.
        /// </summary>
        // ------------------------------------------------------------
        public MotionLayer Targets;

        // ------------------------------------------------------------
        /// <summary>
        /// 적용 순서. 낮을수록 먼저 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        public int Order;

        // ------------------------------------------------------------
        /// <summary>
        /// 같은 순서 안의 등록 순서.
        /// </summary>
        // ------------------------------------------------------------
        public long Sequence;

        // ------------------------------------------------------------
        /// <summary>
        /// 배율 연산.
        /// </summary>
        // ------------------------------------------------------------
        public NumericFOperation Operation;

        // ------------------------------------------------------------
        /// <summary>
        /// 배율 값.
        /// </summary>
        // ------------------------------------------------------------
        public float Value;

        // ------------------------------------------------------------
        /// <summary>
        /// 지속 시간 제한 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasDuration;

        // ------------------------------------------------------------
        /// <summary>
        /// 남은 지속 시간(초).
        /// </summary>
        // ------------------------------------------------------------
        public float Remaining;
    }

    // ============================================================
    /// <summary>
    /// 외부 속도 항목.
    /// </summary>
    // ============================================================
    internal struct MotionExternalEntry
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 항목 식별자.
        /// </summary>
        // ------------------------------------------------------------
        public MotionSourceKey Source;

        // ------------------------------------------------------------
        /// <summary>
        /// 적용 순서. 낮을수록 먼저 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        public int Order;

        // ------------------------------------------------------------
        /// <summary>
        /// 같은 순서 안의 등록 순서.
        /// </summary>
        // ------------------------------------------------------------
        public long Sequence;

        // ------------------------------------------------------------
        /// <summary>
        /// 외부 속도 연산.
        /// </summary>
        // ------------------------------------------------------------
        public NumericFOperation Operation;

        // ------------------------------------------------------------
        /// <summary>
        /// 외부 속도 값.
        /// </summary>
        // ------------------------------------------------------------
        public Vector3 Velocity;

        // ------------------------------------------------------------
        /// <summary>
        /// 지수 감쇠율(1/초). 0이면 감쇠하지 않는다.
        /// </summary>
        // ------------------------------------------------------------
        public float Decay;

        // ------------------------------------------------------------
        /// <summary>
        /// 지속 시간 제한 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasDuration;

        // ------------------------------------------------------------
        /// <summary>
        /// 남은 지속 시간(초).
        /// </summary>
        // ------------------------------------------------------------
        public float Remaining;
    }

    // ======================================================================
    /// <summary>
    /// <br/> Motion Model의 층 항목과 마지막 Tick을 보관하는 Snapshot.
    /// <br/> 같은 Actor·같은 용량의 Model에만 복원할 수 있다.
    /// </summary>
    // ======================================================================
    public sealed class MotionModelSnapshot
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// Snapshot을 만든 Actor.
        /// </summary>
        // ------------------------------------------------------------
        public MotionActorKey Actor { get; internal set; }

        // ------------------------------------------------------------
        /// <summary>
        /// Snapshot 시점의 마지막 실행 Tick. 실행 전이면 -1.
        /// </summary>
        // ------------------------------------------------------------
        public long LastTick { get; internal set; } = -1;

        // ------------------------------------------------------------
        /// <summary>
        /// 층별 항목 용량.
        /// </summary>
        // ------------------------------------------------------------
        public int Capacity { get; }

        internal readonly MotionOverrideEntry[] Overrides;
        internal readonly MotionScaleEntry[] Scales;
        internal readonly MotionExternalEntry[] Externals;
        internal int OverrideCount;
        internal int ScaleCount;
        internal int ExternalCount;
        internal Vector3 AppliedExternal;
        internal long NextSequence;

    #endregion

    #region 생성자

        // ------------------------------------------------------------
        /// <summary>
        /// 층별 용량에 맞는 빈 Snapshot을 만든다.
        /// </summary>
        // ------------------------------------------------------------
        public MotionModelSnapshot(int capacity)
        {
            if (capacity <= 0)
            {
                throw new ArgumentOutOfRangeException(nameof(capacity));
            }

            Capacity = capacity;
            Overrides = new MotionOverrideEntry[capacity];
            Scales = new MotionScaleEntry[capacity];
            Externals = new MotionExternalEntry[capacity];
        }

    #endregion

    }
}
