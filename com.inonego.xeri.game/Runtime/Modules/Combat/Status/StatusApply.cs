using System;

namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// Status 적용 요청의 처리 종류.
    /// </summary>
    // ============================================================
    public enum StatusApplyOutcome { Added, Stacked, Renewed, Rejected }

    // ======================================================================
    /// <summary>
    /// <br/> 이번 Status 적용만의 옵션.
    /// <br/> Spec은 바꾸지 않고 이번 적용이 더할 스택 수와 시작할 스택 시간만 정한다.
    /// </summary>
    // ======================================================================
    public readonly struct StatusApply
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// 이번 적용이 더할 스택 수. 1 이상이어야 한다.
        /// </summary>
        // ------------------------------------------------------------
        public int Stacks { get; }

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> 이번 적용이 시작하는 스택 시간. null이면 Spec.Duration을 쓴다.
        /// <br/> 지속 시간이 없는 Spec에는 지정할 수 없다.
        /// </summary>
        // ----------------------------------------------------------------------
        public float? Duration { get; }

    #endregion

    #region 생성자

        // ------------------------------------------------------------
        /// <summary>
        /// 스택 수와 선택적 스택 시간으로 적용 옵션을 만든다.
        /// </summary>
        // ------------------------------------------------------------
        public StatusApply(int stacks = 1, float? duration = null)
        {
            Stacks = stacks;
            Duration = duration;
        }

    #endregion

    }

    // ================================================================================
    /// <summary>
    /// <br/> Status 적용의 결과.
    /// <br/> 처리 종류와 이번 적용으로 늘어난 스택 수, 최대치 처리로 밀려난 스택 수를 담는다.
    /// </summary>
    // ================================================================================
    public readonly struct StatusApplyResult
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// 처리 종류를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        public StatusApplyOutcome Outcome { get; }

        // ----------------------------------------------------------------------
        /// <summary>
        /// 이번 적용으로 늘어난 스택 수를 반환한다. 거절과 갱신만 한 경우는 0이다.
        /// </summary>
        // ----------------------------------------------------------------------
        public int StacksAdded { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 최대치 처리로 밀려난 기존 스택 수를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        public int StacksReplaced { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 거절됐는지 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsRejected => Outcome == StatusApplyOutcome.Rejected;

    #endregion

    #region 생성자

        // ------------------------------------------------------------
        /// <summary>
        /// 처리 종류와 스택 수 변화로 결과를 만든다.
        /// </summary>
        // ------------------------------------------------------------
        public StatusApplyResult(StatusApplyOutcome outcome, int stacksAdded = 0, int stacksReplaced = 0)
        {
            Outcome = outcome;
            StacksAdded = stacksAdded;
            StacksReplaced = stacksReplaced;
        }

    #endregion

    }
}
