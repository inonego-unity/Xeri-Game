# 설명
StatusContainer.Apply의 적용 옵션과 결과를 정의한다.
옵션은 이번 적용만의 값(스택 수, 지속 시간)을 묶어 시그니처가 위치 인자로 늘어나지 않게 하고, 결과는 처리 종류와 늘거나 밀려난 스택 수를 함께 돌려준다.

# 특이사항, 제약사항
옵션 값의 검사는 Apply가 상태를 바꾸기 전에 한다. default(StatusApply)는 스택 수가 0이라 Apply가 거절하므로 생성자로 만든다.
Duration은 이번 적용이 시작하거나 다시 시작하는 스택 시간에만 쓰이며 Spec.Duration을 바꾸지 않는다.
