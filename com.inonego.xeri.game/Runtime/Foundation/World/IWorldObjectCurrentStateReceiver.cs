namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// 이미 연결된 State를 다른 확정 인스턴스로 교체할 수 있는 선택적 계약.
    /// </summary>
    // ============================================================
    public interface IWorldObjectCurrentStateReceiver
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 타입·ID·적용 가능성을 검사한다. 상태를 변경하지 않아야 한다.
        /// </summary>
        // ------------------------------------------------------------
        void ValidateCurrentState(WorldObjectState state);

        // ------------------------------------------------------------
        /// <summary>
        /// 과거 게임플레이 보상/효과를 재실행하지 않고 현재 상태를 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        void ApplyCurrentState(WorldObjectState state);
    }
}
